'use client';

import { Suspense, useMemo, useState } from 'react';
import { useRouter, useSearchParams } from 'next/navigation';
import { Alert, App, Button, Form, Input, Select, Upload } from 'antd';
import { DatePicker } from '@/components/masked-date-picker';
import dayjs from 'dayjs';
import type { ColumnsType } from 'antd/es/table';
import type { UploadProps } from 'antd';
import { EntityTable, KpiCard, MoneyText, PageHeader, UiCard } from '@zitaware/ui';
import { trpc } from '@/server/trpc';
import { LegalEntitySelect } from '@/components/legal-entity-select';
import { formatMoney } from '@/lib/format';
import type { SalaryImportPreviewRow } from '@zitaware/contracts';
import { formatSalaryMonth, newIdempotencyKey, parseCsv, RowStatusTag, type ParsedRow } from './shared';
import { isoDate } from '@/lib/dates';

interface DraftLine {
  id: string;
  employeeId: string;
  employeeCode: string;
  employeeName: string;
  grossSalaryAmount: string;
}

const SAMPLE = 'Asha Patel,60000\nRavi Shah,45000';

/**
 * Generate → review → commit (ADR-098).
 *
 * The month's batch is produced from each employee's effective salary
 * revision rather than typed in every month. A CSV is still accepted, but as
 * a correction applied to the generated draft — exceptions like a joiner,
 * unpaid leave or a bonus — not as the only way in.
 */
export default function NewSalaryImportPage() {
  // useSearchParams requires a Suspense boundary above it.
  return (
    <Suspense fallback={null}>
      <NewSalaryImportForm />
    </Suspense>
  );
}

function NewSalaryImportForm() {
  const router = useRouter();
  // A draft generated by the hourly worker — or one you walked away from — is
  // reopened here by id. Without this, `draftId` could only ever be set by
  // clicking Generate in this page session, so the worker's own drafts were
  // visible on the list and impossible to act on.
  const seededDraftId = useSearchParams().get('draftId');
  const { message } = App.useApp();
  const utils = trpc.useUtils();
  const [idempotencyKey] = useState(newIdempotencyKey());

  const [legalEntityId, setLegalEntityId] = useState<string | undefined>(undefined);
  const [salaryMonth, setSalaryMonth] = useState<string | undefined>(undefined);
  const [accountingDate, setAccountingDate] = useState<string | undefined>(undefined);
  const [draftId, setDraftId] = useState<string | null>(seededDraftId);
  const [rawText, setRawText] = useState('');
  const [sourceFileName, setSourceFileName] = useState<string | undefined>(undefined);

  const legalEntities = trpc.legalEntities.list.useQuery();
  const draft = trpc.salaryImports.getDetail.useQuery({ id: draftId ?? '' }, { enabled: draftId !== null });
  const lines = (draft.data?.lines ?? []) as DraftLine[];

  const parsedRows: ParsedRow[] = useMemo(() => parseCsv(rawText), [rawText]);
  // The sheet is checked by the server before it is applied: a name becomes
  // its employee code, and a name several employees share is asked about.
  const [chosenCodes, setChosenCodes] = useState<Record<number, string>>({});
  const correction = trpc.salaryImports.preview.useQuery(
    { legalEntityId: draft.data?.legalEntityId ?? '', salaryMonth: draft.data?.salaryMonth ?? '', rows: parsedRows },
    { enabled: !!draft.data && parsedRows.length > 0 },
  );
  const checkedRows = parsedRows.length > 0 ? (correction.data?.rows ?? []) : [];
  const codeFor = (row: SalaryImportPreviewRow) => (row.status === 'AMBIGUOUS' ? (chosenCodes[row.rowNumber] ?? row.suggestedEmployeeCode) : row.employeeCode);
  const blockedRows = checkedRows.filter((row) => (row.status === 'AMBIGUOUS' ? !codeFor(row) : row.status !== 'MATCHED'));
  const resolvedRows: ParsedRow[] = checkedRows.map((row) => ({
    employeeCode: codeFor(row) ?? '',
    employeeName: row.employeeName ?? undefined,
    grossSalaryAmount: row.grossSalaryAmount,
  }));

  // The batch already carries an accounting date (month-end, when generated).
  // Falling back to it means a reopened draft can be committed without
  // re-entering a date, while an explicit choice still wins.
  const effectiveAccountingDate = accountingDate ?? draft.data?.accountingDate;
  // A reopened draft shows its own legal entity; a new one starts on the only
  // legal entity when there is just one.
  const activeLegalEntities = legalEntities.data ?? [];
  const effectiveLegalEntityId =
    legalEntityId ?? draft.data?.legalEntityId ?? (activeLegalEntities.length === 1 ? activeLegalEntities[0]!.id : undefined);

  const generateMutation = trpc.salaryImports.generateDraft.useMutation({
    onSuccess: (batch) => {
      setDraftId(batch.id);
      setAccountingDate((current) => current ?? batch.accountingDate);
      message.success(`Draft generated for ${formatSalaryMonth(batch.salaryMonth)}.`);
    },
    onError: (error) => message.error(error.message),
  });

  const replaceMutation = trpc.salaryImports.replaceDraftRows.useMutation({
    onSuccess: () => {
      message.success('Draft updated from the sheet.');
      setRawText('');
      setChosenCodes({});
      void utils.salaryImports.getDetail.invalidate();
    },
    onError: (error) => message.error(error.message),
  });

  const discardMutation = trpc.salaryImports.discardDraft.useMutation({
    onSuccess: () => {
      message.success('Draft discarded.');
      setDraftId(null);
    },
    onError: (error) => message.error(error.message),
  });

  const commitMutation = trpc.salaryImports.commit.useMutation({
    onSuccess: (batch) => {
      message.success(`${formatSalaryMonth(batch.salaryMonth)} posted — ${formatMoney(batch.totalGrossAmount)} across ${batch.employeeCount} employees.`);
      router.push('/employee-costing?tab=salary');
    },
    onError: (error) => message.error(error.message),
  });

  const columns: ColumnsType<DraftLine> = [
    { title: 'Code', dataIndex: 'employeeCode', key: 'employeeCode', render: (v: string) => <span className="font-mono text-[12px]">{v}</span> },
    { title: 'Employee', dataIndex: 'employeeName', key: 'employeeName' },
    {
      title: 'Gross Salary',
      dataIndex: 'grossSalaryAmount',
      key: 'grossSalaryAmount',
      align: 'right',
      render: (v: string) => <MoneyText tone="neutral">{formatMoney(v)}</MoneyText>,
    },
  ];

  const beforeUpload: UploadProps['beforeUpload'] = (file) => {
    const reader = new FileReader();
    reader.onload = () => {
      setRawText(String(reader.result ?? ''));
      setSourceFileName(file.name);
    };
    reader.onerror = () => message.error('Could not read that file.');
    reader.readAsText(file);
    // Parsed in the browser; only the rows are sent, so there is no upload to
    // clean up if the commit later fails.
    return false;
  };

  return (
    <>
      <PageHeader
        title="Import Monthly Salary"
        description="Generated from each employee's salary on record, then reviewed and committed. Posts Dr Salaries & Wages Expense / Cr Salary Payable."
        actions={
          <Button size="small" onClick={() => router.push('/employee-costing?tab=salary')}>
            Back
          </Button>
        }
      />

      <UiCard className="mb-4">
        <div className="grid grid-cols-1 gap-3 md:grid-cols-3">
          <Form.Item label="Legal entity" required className="mb-0">
            <LegalEntitySelect value={effectiveLegalEntityId} onChange={setLegalEntityId} disabled={draftId !== null} />
          </Form.Item>
          <Form.Item label="Salary month" required className="mb-0" tooltip="Any day in the month works — the month itself is the identity of the import.">
            <DatePicker
              picker="month"
              className="w-full"
              disabled={draftId !== null}
              // A reopened draft shows the month it is for, rather than an
              // empty box next to rows that clearly belong to some month.
              value={salaryMonth ? dayjs(salaryMonth) : draft.data ? dayjs(draft.data.salaryMonth) : null}
              onChange={(_d, s) => setSalaryMonth(typeof s === 'string' && s ? `${s}-01` : undefined)}
            />
          </Form.Item>
          <Form.Item label=" " className="mb-0">
            <Button
              type="primary"
              block
              loading={generateMutation.isPending}
              disabled={!effectiveLegalEntityId || !salaryMonth || draftId !== null}
              onClick={() => generateMutation.mutate({ legalEntityId: effectiveLegalEntityId!, salaryMonth: salaryMonth! })}
            >
              Generate Draft
            </Button>
          </Form.Item>
        </div>
      </UiCard>

      {draft.data ? (
        <>
          <div className="mb-4 grid grid-cols-1 gap-3 sm:grid-cols-3">
            <KpiCard label="Month" value={formatSalaryMonth(draft.data.salaryMonth)} />
            <KpiCard label="Employees" value={draft.data.employeeCount} sub="From salary revisions on record" />
            <KpiCard
              label="Gross Salary"
              value={<MoneyText tone="neutral">{formatMoney(draft.data.totalGrossAmount)}</MoneyText>}
            />
          </div>

          <UiCard className="mb-4" title="Corrections (optional)">
            <div className="mb-3 flex flex-wrap items-center gap-3">
              <Upload beforeUpload={beforeUpload} showUploadList={false} accept=".csv,text/csv">
                <Button>Upload CSV</Button>
              </Upload>
              <span className="text-[12px] text-muted">
                Replaces every row — use it for exceptions like a joiner, unpaid leave or a bonus month. Columns: name, gross
                salary. The employee code is filled in from the name; when two employees share a name you choose which.
                Export an .xlsx sheet to CSV first.
              </span>
              {sourceFileName ? <span className="text-[12px] font-semibold text-ink">{sourceFileName}</span> : null}
            </div>
            <Input.TextArea
              rows={4}
              value={rawText}
              onChange={(e) => {
                setRawText(e.target.value);
                setSourceFileName(undefined);
              }}
              placeholder={`Paste rows to replace the generated ones. For example:\n${SAMPLE}`}
              className="font-mono"
            />
            {checkedRows.length > 0 ? (
              <table className="mt-3 w-full text-[12.5px]">
                <thead>
                  <tr className="border-b border-ui text-left text-muted">
                    <th className="py-1.5 pr-3 font-medium">Row</th>
                    <th className="py-1.5 pr-3 font-medium">Name in sheet</th>
                    <th className="py-1.5 pr-3 font-medium">Employee</th>
                    <th className="py-1.5 pr-3 text-right font-medium">Gross salary</th>
                    <th className="py-1.5 pr-3 font-medium">Check</th>
                  </tr>
                </thead>
                <tbody>
                  {checkedRows.map((row) => (
                    <tr key={row.rowNumber} className="border-b border-ui-2 align-top last:border-b-0">
                      <td className="py-1.5 pr-3 text-muted">{row.rowNumber}</td>
                      <td className="py-1.5 pr-3 text-ink">{row.employeeName ?? '—'}</td>
                      <td className="py-1.5 pr-3">
                        {row.status === 'AMBIGUOUS' ? (
                          <Select
                            size="small"
                            className="w-[300px]"
                            placeholder="Which one? Choose by code"
                            {...(codeFor(row) ? { value: codeFor(row)! } : {})}
                            onChange={(code: string) => setChosenCodes((current) => ({ ...current, [row.rowNumber]: code }))}
                            options={row.candidates.map((c) => ({
                              value: c.employeeCode,
                              label: `${c.employeeCode} · ${c.fullName}${c.currentSalary ? ` · now ${formatMoney(c.currentSalary)}` : ''}${c.employeeCode === row.suggestedEmployeeCode ? ' (suggested: same salary)' : ''}`,
                            }))}
                          />
                        ) : row.employeeCode ? (
                          <span>
                            <span className="font-mono text-[12px]">{row.employeeCode}</span> {row.matchedEmployeeName ?? ''}
                          </span>
                        ) : (
                          '—'
                        )}
                      </td>
                      <td className="py-1.5 pr-3 text-right tabular-nums">{formatMoney(row.grossSalaryAmount)}</td>
                      <td className="py-1.5 pr-3">
                        {row.status === 'MATCHED' || (row.status === 'AMBIGUOUS' && codeFor(row)) ? (
                          <RowStatusTag status="MATCHED" />
                        ) : (
                          <span className="text-negative">{row.message}</span>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            ) : null}
            <div className="mt-2 flex justify-end">
              <Button
                loading={replaceMutation.isPending || correction.isFetching}
                disabled={parsedRows.length === 0 || checkedRows.length === 0 || blockedRows.length > 0}
                onClick={() => replaceMutation.mutate({ id: draftId!, sourceFileName, rows: resolvedRows })}
              >
                Apply {checkedRows.length > 0 ? `${checkedRows.length} row(s)` : 'sheet'}
              </Button>
            </div>
          </UiCard>

          <UiCard flush>
            <EntityTable<DraftLine>
              rowKey="id"
              columns={columns}
              dataSource={lines}
              loading={draft.isLoading}
              errorMessage={draft.isError ? 'Could not load the draft. Please retry.' : undefined}
              emptyTitle="This draft has no rows"
              emptyDescription="Apply a sheet above, or discard the draft and record salaries first."
              page={1}
              pageSize={lines.length || 1}
              total={lines.length}
              onPageChange={() => undefined}
            />
          </UiCard>

          <div className="mt-4 flex flex-wrap items-end justify-between gap-3 border-t border-ui pt-3">
            <Form.Item
              label="Accounting date"
              required
              className="mb-0"
              tooltip="Normally month-end. This resolves the accounting period the cost lands in, and cannot fall before the month itself."
>
              <DatePicker
                className="w-[200px]"
                value={effectiveAccountingDate ? dayjs(effectiveAccountingDate) : null}
                onChange={(picked) => setAccountingDate(isoDate(picked) || undefined)}
              />
            </Form.Item>
            <div className="flex gap-2">
              <Button
                danger
                loading={discardMutation.isPending}
                onClick={() => discardMutation.mutate({ id: draftId! })}
              >
                Discard Draft
              </Button>
              <Button
                type="primary"
                loading={commitMutation.isPending}
                disabled={!effectiveAccountingDate || lines.length === 0}
                onClick={() => commitMutation.mutate({ id: draftId!, accountingDate: effectiveAccountingDate!, idempotencyKey })}
              >
                Commit Import
              </Button>
            </div>
          </div>
        </>
      ) : (
        <Alert
          type="info"
          showIcon
          message="Pick a legal entity and month, then generate"
          description="The draft is built from each active employee's salary revision effective for that month. Nothing posts until you review and commit it."
        />
      )}
    </>
  );
}
